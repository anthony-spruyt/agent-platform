using AgentPlatform.Host.RenovateTriage;

namespace AgentPlatform.Tests.RenovateTriage;

public class RenovateRebaseBoxTests
{
    private const string Open = " - [ ] <!-- rebase-check -->If you want to rebase/retry this PR, check this box";
    private const string Ticked = " - [x] <!-- rebase-check -->If you want to rebase/retry this PR, check this box";

    private static string BodyWith(string boxLine, string newline = "\n") =>
        string.Join(newline, "This PR contains the following updates:", "", "- [ ] a task list item in the notes", "", "---", "", boxLine, "", "---", "", "- [ ] <!-- other-check -->Another box", "", "This PR was generated by Mend Renovate.");

    [Fact]
    public void Tick_ChecksTheRebaseBoxAndNothingElse()
    {
        var body = BodyWith(Open);

        var result = RenovateRebaseBox.Tick(body);

        Assert.Equal(RebaseBoxState.Ticked, result.State);
        Assert.Equal(BodyWith(Ticked), result.Body);
    }

    [Fact]
    public void Tick_KeepsWindowsLineEndings()
    {
        var result = RenovateRebaseBox.Tick(BodyWith(Open, "\r\n"));

        Assert.Equal(RebaseBoxState.Ticked, result.State);
        Assert.Equal(BodyWith(Ticked, "\r\n"), result.Body);
    }

    [Theory]
    [InlineData("x")]
    [InlineData("X")]
    public void Tick_WhenTheBoxIsAlreadyChecked_LeavesTheBodyAlone(string mark)
    {
        var body = BodyWith(Open.Replace("[ ]", $"[{mark}]", StringComparison.Ordinal));

        var result = RenovateRebaseBox.Tick(body);

        Assert.Equal(RebaseBoxState.AlreadyTicked, result.State);
        Assert.Equal(body, result.Body);
    }

    [Fact]
    public void Tick_WithoutTheMarker_ReportsItMissing()
    {
        var body = "A body by hand.\n\n- [ ] not the rebase box\n";

        var result = RenovateRebaseBox.Tick(body);

        Assert.Equal(RebaseBoxState.Missing, result.State);
        Assert.Equal(body, result.Body);
    }

    [Fact]
    public void Tick_IgnoresTheMarkerWhenItIsQuotedInsideAParagraph()
    {
        var body = "Renovate's box reads `- [ ] <!-- rebase-check -->` in the body.";

        var result = RenovateRebaseBox.Tick(body);

        Assert.Equal(RebaseBoxState.Missing, result.State);
    }

    [Fact]
    public void Tick_WithAnEmptyBody_ReportsTheBoxMissing()
    {
        Assert.Equal(RebaseBoxState.Missing, RenovateRebaseBox.Tick(string.Empty).State);
    }

    [Fact]
    public void Tick_TwiceYieldsOneTick()
    {
        var first = RenovateRebaseBox.Tick(BodyWith(Open));

        var second = RenovateRebaseBox.Tick(first.Body);

        Assert.Equal(RebaseBoxState.AlreadyTicked, second.State);
        Assert.Equal(first.Body, second.Body);
    }
}
