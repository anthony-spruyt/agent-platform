using System.Net;
using AgentPlatform.Host.GitHub;
using AgentPlatform.Host.PullRequests;
using AgentPlatform.Host.RenovateTriage;
using AgentPlatform.Host.RunData;
using AgentPlatform.Host.Workflows;
using AgentPlatform.Tests.Support;
using Temporalio.Client;
using Temporalio.Exceptions;
using Temporalio.Testing;

namespace AgentPlatform.Tests.Workflows;

public partial class RenovateTriageWorkflowTests
{
    private const string RebaseBoxLine = " - [ ] <!-- rebase-check -->If you want to rebase/retry this PR, check this box";
    private const string RenovateBody = FakeGitHubApi.Body + "\n---\n\n" + RebaseBoxLine + "\n\n---\n\nThis PR was generated by Mend Renovate.";

    private static Rig RefusedRerunRig()
    {
        var rig = new Rig { Mode = TriageMode.Live };
        FailCi(rig);
        rig.Jev.CiKind = CiFailureKind.Flaky;
        rig.Github.RerunFailures[900] = new GitHubApiException("GitHub failed jobs rerun failed with status 403.", HttpStatusCode.Forbidden, responseMessage: "This workflow run cannot be retried");
        rig.Github.PullRequest = FakeGitHubApi.Renovate(body: RenovateBody);
        return rig;
    }

    private static void RenovatePushes(Rig rig)
    {
        rig.Github.PullRequest = FakeGitHubApi.Renovate(sha: ShaB, body: RenovateBody);
        rig.Github.Commits[0] = FakeGitHubApi.RenovateCommit(ShaB);
    }

    private static async Task<RenovateTriageResult> SignalThroughTheSignalerAsync(WorkflowEnvironment env, CheckSuiteCompletedSignal signal)
    {
        await SignalAsync(env, signal);
        var latest = env.Client.GetWorkflowHandle<RenovateTriageWorkflow, RenovateTriageResult>(RenovateTriageWorkflow.WorkflowId(signal.Repo, signal.PrNumber));
        return await latest.GetResultAsync(rpcOptions: new RpcOptions { CancellationToken = Ct });
    }

    [Fact]
    public async Task AFlakyFailureGitHubWillNotRerun_TicksTheRenovateBoxOnce_RecordsIt_AndEndsWithoutAVerdict()
    {
        await using var env = await WorkflowEnvironment.StartTimeSkippingAsync();
        var rig = RefusedRerunRig();

        var result = await InWorkerAsync(env, rig, async () => await RunToResultAsync(await StartAsync(env, Signal()), "renovate-triage-rebase-requested"));

        Assert.Equal(new RenovateTriageResult(RenovateTriageOutcome.Rebased, ShaA, TriageRules.RebaseRequested, null), result);
        Assert.Equal([900L], rig.Github.RerunAttempts);
        Assert.Equal([RenovateBody.Replace("- [ ] <!-- rebase-check -->", "- [x] <!-- rebase-check -->", StringComparison.Ordinal)], rig.Github.BodyWrites);
        Assert.Equal(ShaA, (await rig.Data.Rebases.FindAsync(Repo, 7, Ct))?.HeadSha);
        Assert.Empty(await VerdictsAsync(rig));
        Assert.Null(await rig.Data.Pending.FindAsync(Repo, 7, Ct));
        Assert.Empty(rig.Github.AddedLabels);
        Assert.Contains(await StepsAsync(rig), s => s is { Name: "ci-rerun", StopReason: "rebase" });
    }

    [Fact]
    public async Task AfterARebaseRequest_TheTriageCheckEndsNeutral_SoItDoesNotReadAsAFailure()
    {
        await using var env = await WorkflowEnvironment.StartTimeSkippingAsync();
        var rig = RefusedRerunRig();

        await InWorkerAsync(env, rig, async () => await RunToResultAsync(await StartAsync(env, Signal())));

        var last = rig.CheckRuns.Reports[^1];
        Assert.Equal((ShaA, CheckRunStatus.Completed, CheckRunConclusion.Neutral), (last.HeadSha, last.Status, last.Conclusion));
        Assert.Contains("rebase", last.Summary, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public async Task ANewHeadAfterARebaseRequest_StartsTheTriageNormally_AndTicksNothingAgain()
    {
        await using var env = await WorkflowEnvironment.StartTimeSkippingAsync();
        var rig = RefusedRerunRig();

        var (first, second) = await InWorkerAsync(env, rig, async () =>
        {
            var first = await RunToResultAsync(await StartAsync(env, Signal()));
            RenovatePushes(rig);
            PassCi(rig);
            var second = await SignalThroughTheSignalerAsync(env, Signal(ShaB, suite: 2));
            return (first, second);
        });

        Assert.Equal(RenovateTriageOutcome.Rebased, first.Outcome);
        Assert.Equal(new RenovateTriageResult(RenovateTriageOutcome.Judged, ShaB, TriageRules.ChangelogPresent, TriageVerdict.Approve), second);
        Assert.Equal([ShaB], rig.Github.Approvals.Select(a => a.CommitId));
        Assert.Single(rig.Github.BodyWrites);
        Assert.Equal([900L], rig.Github.RerunAttempts);
    }

    [Fact]
    public async Task AnotherSuiteCompletingOnTheRebasedHead_EndsTheSameWay_WithoutTickingTwice()
    {
        await using var env = await WorkflowEnvironment.StartTimeSkippingAsync();
        var rig = RefusedRerunRig();

        var (first, second) = await InWorkerAsync(env, rig, async () =>
        {
            var first = await RunToResultAsync(await StartAsync(env, Signal()));
            var second = await SignalThroughTheSignalerAsync(env, Signal(suite: 2));
            return (first, second);
        });

        Assert.Equal(first, second);
        Assert.Single(rig.Github.BodyWrites);
        Assert.Empty(await VerdictsAsync(rig));
        Assert.Equal(CheckRunConclusion.Neutral, rig.CheckRuns.Reports[^1].Conclusion);
    }

    [Fact]
    public async Task ASecondUnrerunnableFailureOnTheSamePullRequest_HandsOffToTheOwner_InsteadOfRebasingAgain()
    {
        await using var env = await WorkflowEnvironment.StartTimeSkippingAsync();
        var rig = RefusedRerunRig();

        var (first, second) = await InWorkerAsync(env, rig, async () =>
        {
            var first = await RunToResultAsync(await StartAsync(env, Signal()));
            RenovatePushes(rig);
            var second = await RunToResultAsync(await StartAsync(env, Signal(ShaB, suite: 2)), "renovate-triage-rebase-limit");
            return (first, second);
        });

        Assert.Equal(RenovateTriageOutcome.Rebased, first.Outcome);
        Assert.Equal((ShaB, TriageVerdict.Owner), (second.HeadSha, second.Verdict));
        Assert.Equal(TriageRules.CiFailed, (await PendingAsync(rig)).Reason);
        Assert.Single(rig.Github.BodyWrites);
        Assert.Equal([900L, 900L], rig.Github.RerunAttempts);
    }

    [Fact]
    public async Task ABodyWithoutTheRenovateBox_HandsTheFailureToTheOwner()
    {
        await using var env = await WorkflowEnvironment.StartTimeSkippingAsync();
        var rig = RefusedRerunRig();
        rig.Github.PullRequest = FakeGitHubApi.Renovate();

        var result = await InWorkerAsync(env, rig, async () => await RunToResultAsync(await StartAsync(env, Signal())));

        Assert.Equal(TriageVerdict.Owner, result.Verdict);
        Assert.Equal(TriageRules.CiFailed, (await PendingAsync(rig)).Reason);
        Assert.Empty(rig.Github.BodyWrites);
        Assert.Null(await rig.Data.Rebases.FindAsync(Repo, 7, Ct));
    }

    [Fact]
    public async Task APermissionRefusalOfTheRerun_StillFailsTheWorkflow_WithoutTouchingTheBody()
    {
        await using var env = await WorkflowEnvironment.StartTimeSkippingAsync();
        var rig = RefusedRerunRig();
        rig.Github.RerunFailures[900] = new GitHubApiException("GitHub failed jobs rerun failed with status 403.", HttpStatusCode.Forbidden, responseMessage: "Resource not accessible by integration");

        await InWorkerAsync(env, rig, async () =>
        {
            var handle = await StartAsync(env, Signal());
            await Assert.ThrowsAsync<WorkflowFailedException>(() => RunToResultAsync(handle));
            return 0;
        });

        Assert.Empty(rig.Github.BodyWrites);
        Assert.Null(await rig.Data.Rebases.FindAsync(Repo, 7, Ct));
        Assert.True(rig.Github.RerunAttempts.Count > 1, "A permission refusal should be retried as an ordinary failure.");
    }
}
